const express = require('express');
const router = express.Router();
const c = require('../controllers/candidature.controller');
const { authenticateToken: auth } = require('../middlewares/auth.middleware');
const { requireRole: role } = require('../middlewares/role.middleware');
const { withScope } = require('../middlewares/authorization.middleware');
const { createApplicationValidation, updateApplicationStatusValidation, stagePreferencesValidation, onboardingDocumentValidation, documentVerificationDecisionValidation, documentDownloadValidation } = require('../validators/application.validator');
const { validate } = require('../validators');
const documentService = require('../services/document.service');
router.use(auth);
router.get('/', withScope, c.getAll);
router.get('/mes-offres', role('CANDIDAT'), c.getMyOffers);
router.get('/mes-candidatures', role('CANDIDAT'), c.getMyCandidatures);
router.get('/:id/entretien-ia', role('CANDIDAT'), c.getAiInterview);
router.get('/:id/entretien-humain', role('CANDIDAT', 'STAGIAIRE'), c.getCandidateHumanInterview);
router.get('/:id/internship-access', role('CANDIDAT'), c.getInternshipAccess);
router.get('/:id/internship-readiness', withScope, role('CANDIDAT', 'RH', 'ADMIN'), c.getInternshipReadiness);
router.post('/:id/convert-to-trainee', role('RH', 'ADMIN'), c.convertToTrainee);
// Raccourci DEMO : acceptation directe d'une candidature AI_INTERVIEW_PASSED
// (crée le stage sans passer par l'entretien humain). Voir candidature.service.js.
router.post('/:id/accept-after-ai-interview', role('RH', 'ADMIN'), c.acceptAfterAiInterview);
router.put('/:id/stage-preferences', role('CANDIDAT'), stagePreferencesValidation, validate, c.submitStagePreferences);
router.post('/:id/stage-preferences/validate', role('RH', 'ADMIN'), c.validateStagePreferences);
router.post('/:id/stage-preferences/request-modification', role('RH', 'ADMIN'), c.requestStagePreferencesModification);
router.post('/:id/entretien-ia/result', role('RH', 'ADMIN'), c.submitAiInterviewResult);
router.post('/:id/entretien-humain', role('RH', 'ADMIN'), c.scheduleHumanInterview);
router.post('/:id/entretien-humain/express', role('RH', 'ADMIN'), c.scheduleExpressHumanInterview);
router.put('/:id/entretien-humain', role('RH', 'ADMIN'), c.updateHumanInterview);
router.delete('/:id/entretien-humain', role('RH', 'ADMIN'), c.cancelHumanInterview);
router.post('/:id/entretien-humain/completion', role('RH', 'ADMIN'), c.completeHumanInterview);
router.post('/:id/entretien-humain/decision', role('RH', 'ADMIN'), c.decideHumanInterview);
router.post('/:id/decision-finale', withScope, role('RH', 'ADMIN'), c.recordHumanInterviewDecision);
router.post('/:id/documents/:type', role('CANDIDAT', 'STAGIAIRE'), documentService.uploadMiddleware, onboardingDocumentValidation, documentService.validateUpload, c.uploadOnboardingDocument);
router.patch('/:id/documents/:documentId/verification', role('RH', 'ADMIN'), documentVerificationDecisionValidation, validate, c.decideDocumentVerification);
router.get('/:id/documents/:documentId/download', role('RH', 'ADMIN'), documentDownloadValidation, validate, c.downloadOnboardingDocument);
router.get('/:id', role('CANDIDAT', 'RH', 'ADMIN'), c.getById);
router.get('/:id/cv', role('CANDIDAT', 'RH', 'ADMIN'), c.downloadCv);
router.post('/', role('STAGIAIRE', 'CANDIDAT', 'ADMIN', 'RH'), createApplicationValidation, validate, c.create);
router.put('/:id', withScope, role('ADMIN', 'RH'), updateApplicationStatusValidation, validate, c.updateStatut);
router.delete('/:id', withScope, role('ADMIN', 'RH'), c.delete);
module.exports = router;
