const express = require('express');
const router = express.Router();
const c = require('../controllers/stagiaire.controller');
const { getOverview, getMonProjet, getCalendar, getCompletion } = require('../controllers/stagiaire-overview.controller');
const { authenticateToken: auth } = require('../middlewares/auth.middleware');
const { requireRole: role } = require('../middlewares/role.middleware');
const { withScope, authorizeResource } = require('../middlewares/authorization.middleware');
const { createInternValidation } = require('../validators/intern.validator');
const { validate } = require('../validators');
router.use(auth, withScope);
router.get('/overview', getOverview);
router.get('/projet', getMonProjet);
router.get('/calendar', getCalendar);
router.get('/completion', getCompletion);
router.get('/', c.getAll);
router.get('/:id', authorizeResource('stagiaire'), c.getById);
router.post('/', role('ADMIN', 'RH'), createInternValidation, validate, c.create);
router.put('/:id', role('ADMIN', 'RH'), c.update);
router.delete('/:id', role('ADMIN', 'RH'), c.delete);
module.exports = router;
